"""Generate reports/results/results_tables.md + comparisons.json from runs/ (no hand-typed numbers).

Runs the pre-registered comparisons with the paired bootstrap (src/experiments/aggregate.py):
  M1   C_ST_risk_head128 vs C_ST_risk_headtail256 (and head256 if present)       VALIDATION (selection only)
  M2   C_ST_sentiment_muril vs C_ST_sentiment_hingroberta                        VALIDATION + TEST
  ABL  C_MT_muril vs C_ST_{sentiment,emotion,risk}_muril                         TEST (pre-registered)
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src.config import REPORTS_DIR  # noqa: E402
from src.experiments.aggregate import collect, paired_bootstrap, summarise  # noqa: E402
from src.experiments.runner import runs_dir  # noqa: E402

R = runs_dir()
done = {p.name for p in R.glob("*") if list(p.glob("seed_*/metrics.json"))}
COMPARISONS = [
    ("M1", "C_ST_risk_head128", "C_ST_risk_headtail256", "val", "risk", m, None) for m in ("macro_f1", "pr_auc", "roc_auc", "f1")
] + [
    ("M1", "C_ST_risk_head128", "C_ST_risk_head256", "val", "risk", m, None) for m in ("macro_f1", "pr_auc")
] + [
    ("M2", "C_ST_sentiment_muril", "C_ST_sentiment_hingroberta", split, "sentiment", "macro_f1", scope)
    for split in ("val", "test") for scope in (None, "language:hi-Latn", "language:en-Latn", "source:tweets-hindi", "source:youtube-hinglish", "source:tweets-english")
] + [
    ("ABL", {"risk": "C_ST_risk_head128"}.get(t, f"C_ST_{t}_muril"), "C_MT_muril", "test", t, m, None)
    for t, ms in (("sentiment", ("macro_f1",)), ("emotion", ("macro_f1",)), ("risk", ("macro_f1", "pr_auc", "f1")))
    for m in ms
] + [("ABL", "C_ST_sentiment_muril", "C_MT_muril", "test", "sentiment", "macro_f1", s) for s in ("language:hi-Latn", "language:en-Latn")
] + [("ABL", "C_ST_emotion_muril", "C_MT_muril", "test", "emotion", "macro_f1", s) for s in ("language:en-Latn", "language:hi-Deva")]


def fmt(x, d=3):
    return "n/a" if x is None or x != x else f"{x:.{d}f}"


if __name__ == "__main__":
    out = REPORTS_DIR / "results"
    out.mkdir(parents=True, exist_ok=True)
    comps = []
    for tag, a, b, split, task, metric, scope in COMPARISONS:
        if a not in done or b not in done:
            comps.append({"id": tag, "a": a, "b": b, "split": split, "task": task, "metric": metric, "scope": scope or "all", "status": "NOT RUN (missing runs)"})
            continue
        try:
            r = paired_bootstrap(R, a, b, split, task, metric, scope, n=1000)
            r.update({"id": tag, "status": "ok"})
        except ValueError as e:
            r = {"id": tag, "a": a, "b": b, "split": split, "task": task, "metric": metric, "scope": scope or "all", "status": f"skipped: {e}"}
        comps.append(r)
    (out / "comparisons.json").write_text(json.dumps(comps, indent=2))
    s = summarise(collect(R))
    s.to_csv(out / "summary.csv", index=False)
    L = ["# Results tables (generated by scripts/write_results_tables.py; do not edit by hand)", "",
         "## Per-experiment means over seeds (scope = all)", "",
         "| experiment | split | task | metric | mean | sd | seeds |", "|---|---|---|---|---|---|---|"]
    key = s[(s.scope == "all") & s.metric.isin(["macro_f1", "f1", "precision", "recall", "pr_auc", "roc_auc", "ece", "brier"])]
    for r in key.sort_values(["experiment", "split", "task", "metric"]).itertuples():
        L.append(f"| {r.experiment} | {r.split} | {r.task} | {r.metric} | {fmt(r.mean)} | {fmt(r.sd)} | {r.n_seeds} |")
    L += ["", "## Per-language / per-source macro-F1 (test where available)", "", "| experiment | split | task | scope | mean | sd | seeds |", "|---|---|---|---|---|---|---|"]
    sub = s[(s.scope != "all") & (s.metric == "macro_f1")]
    for r in sub.sort_values(["experiment", "split", "task", "scope"]).itertuples():
        L.append(f"| {r.experiment} | {r.split} | {r.task} | {r.scope} | {fmt(r.mean)} | {fmt(r.sd)} | {r.n_seeds} |")
    L += ["", "## Paired bootstrap comparisons (B - A; 1,000 resamples of examples; seed-averaged metric)", "",
          "| id | split | task | metric | scope | A | B | mean A | mean B | diff | 95% CI | excludes 0 |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for c in comps:
        if c["status"] != "ok":
            L.append(f"| {c['id']} | {c['split']} | {c['task']} | {c['metric']} | {c['scope']} | {c['a']} | {c['b']} | - | - | - | - | {c['status']} |")
            continue
        L.append(f"| {c['id']} | {c['split']} | {c['task']} | {c['metric']} | {c['scope']} | {c['a']} | {c['b']} | {fmt(c['mean_a'])} | {fmt(c['mean_b'])} | "
                 f"{c['diff_b_minus_a']:+.3f} | [{c['ci95'][0]:+.3f}, {c['ci95'][1]:+.3f}] | {'yes' if c['ci_excludes_zero'] else 'no'} |")
    (out / "results_tables.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[-len(comps) - 1:]))
