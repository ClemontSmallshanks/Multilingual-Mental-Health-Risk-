"""Summarise all runs -> reports/results/{experiments.csv, summary.csv, summary.md}.

  python scripts/aggregate_runs.py
  python scripts/aggregate_runs.py --compare R2_muril_multitask_baseline E1_4_stress_final --split test --task risk --metric pr_auc
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src.config import REPORTS_DIR  # noqa: E402
from src.experiments.aggregate import collect, paired_bootstrap, summarise  # noqa: E402
from src.experiments.runner import runs_dir  # noqa: E402

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--compare", nargs=2, metavar=("EXP_A", "EXP_B"))
    ap.add_argument("--split", default="val")
    ap.add_argument("--task", default="risk")
    ap.add_argument("--metric", default="macro_f1")
    ap.add_argument("--scope", default=None, help="e.g. language:hi-Latn or source:youtube-hinglish")
    ap.add_argument("--out", default=str(REPORTS_DIR / "results"))
    a = ap.parse_args()
    if a.compare:
        r = paired_bootstrap(runs_dir(), *a.compare, a.split, a.task, a.metric, a.scope)
        print(json.dumps(r, indent=2))
        out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
        with open(out / "comparisons.jsonl", "a") as f:
            f.write(json.dumps(r) + "\n")
        sys.exit(0)
    df = collect(runs_dir())
    if df.empty:
        sys.exit(f"no completed runs under {runs_dir()}")
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    df.to_csv(out / "experiments.csv", index=False)
    s = summarise(df)
    s.to_csv(out / "summary.csv", index=False)
    key = s[(s.scope == "all") & s.metric.isin(["macro_f1", "f1", "pr_auc", "roc_auc", "ece"])]
    lines = ["# Experiment summary (generated by scripts/aggregate_runs.py - do not edit by hand)", "",
             "| experiment | split | task | metric | mean | sd | n seeds |", "|---|---|---|---|---|---|---|"]
    for r in key.itertuples():
        lines.append(f"| {r.experiment} | {r.split} | {r.task} | {r.metric} | {r.mean:.4f} | {0 if r.sd != r.sd else r.sd:.4f} | {r.n_seeds} |")
    (out / "summary.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
